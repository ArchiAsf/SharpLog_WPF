namespace SharpLog.Model
{
    /// <summary>
    /// 一天中的时段划分（用于晨昏区切换图标与文字）。
    ///
    /// ════════════════════════════════════════════════════════════════════════
    /// 【划分依据】
    ///   以【民用日出/日落时刻】为基准，各自向前后各扩展一段过渡时间
    ///   （当前取 30 分钟，见 SunTimeCalculator.ResolveDayPeriod 的 transition 参数）：
    ///
    ///        ─────┬──────────┬─────┬──────────┬─────
    ///          夜间 │   黎明    │ 日间 │   黄昏    │ 夜间
    ///        ─────┴──────────┴─────┴──────────┴─────
    ///           日出-30′  日出+30′ 日落-30′  日落+30′
    ///
    ///   「黎明」与「黄昏」之所以要单独成段，是因为这两段时间光线变化最快、
    ///   电离层状态也在切换，是业余无线电判断波段开闭的关键窗口。
    ///
    /// 【极昼 / 极夜】
    ///   高纬度地区可能出现太阳整日不落或不升的情况，
    ///   此时没有日出日落可言，单独用 PolarDay / PolarNight 表示。
    /// ════════════════════════════════════════════════════════════════════════
    /// </summary>
    public enum DayPeriod
    {
        /// <summary>黎明：日出前 30 分钟 ~ 日出后 30 分钟。</summary>
        Dawn,

        /// <summary>日间：日出后 30 分钟 ~ 日落前 30 分钟。</summary>
        Day,

        /// <summary>黄昏：日落前 30 分钟 ~ 日落后 30 分钟。</summary>
        Dusk,

        /// <summary>夜间：日落 30 分钟后 ~ 次日日出 30 分钟前。</summary>
        Night,

        /// <summary>极昼：太阳整日不落（无日出日落可算）。</summary>
        PolarDay,

        /// <summary>极夜：太阳整日不升（无日出日落可算）。</summary>
        PolarNight,

        /// <summary>无法判定：尚未填写经纬度，或经纬度格式非法。</summary>
        Unknown
    }
}
